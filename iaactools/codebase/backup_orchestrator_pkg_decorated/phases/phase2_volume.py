from backup_orchestrator_pkg.result_envelope import enveloped

import logging
import json
from pathlib import Path
from iaactools.codebase.utils.integrity_utils import safe_save_json


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------
def _load_phase1_result(cfg, logger):
    """Load Phase 1 output (phase1_init.json) and return inventories."""
    run_id = cfg["audit"]["run_id"]
    path = Path.cwd() / "results" / "backup_audit" / run_id / "phase1_init.json"
    if not path.exists():
        raise FileNotFoundError(f"Phase 1 result not found: {path}")
    logger.info(f"Loading verified Phase 1 result: {path}")
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not data.get("ManifestVerified"):
        raise RuntimeError("Phase 1 manifest verification failed or was skipped.")
    return data.get("Inventories", {})


# -----------------------------------------------------------------------------
# Main Phase Entry
# -----------------------------------------------------------------------------
@enveloped(schema={'cfg': {'type': dict, 'required': True}, 'logger': {'required': True}})
def run(cfg: dict, logger: logging.Logger) -> dict:
    """Phase 2 — Volume pre-backup validation using Phase 1 inventories."""
    simulate = bool(cfg.get("audit", {}).get("simulate", False))
    run_id = cfg["audit"]["run_id"]

    result = {
        "Phase": "VolumePrep",
        "AWSProfile": cfg["audit"]["profile"],
        "Region": cfg["audit"]["region"],
        "ValidatedVolumes": 0,
        "RegionsProcessed": [],
        "Status": "FAILED",
        "Error": None,
        "Simulate": simulate,
        "IntegrityHash": None,
    }

    results_dir = Path.cwd() / "results" / "backup_audit" / run_id
    results_dir.mkdir(parents=True, exist_ok=True)
    out_path = results_dir / "phase2_volume.json"

    # ----------------------------------------------------------------------
    # 🧪 Simulation Mode
    # ----------------------------------------------------------------------
    if simulate:
        logger.warning("[SIMULATION MODE] Phase 2 running with synthetic data.")
        result.update({
            "ValidatedVolumes": 1,
            "RegionsProcessed": ["us-east-1"],
            "Status": "SUCCESS",
        })
        result["IntegrityHash"] = safe_save_json(result, out_path, logger)
        return result

    # ----------------------------------------------------------------------
    # 1️⃣ Load verified inventories from Phase 1
    # ----------------------------------------------------------------------
    try:
        inventories = _load_phase1_result(cfg, logger)
    except Exception as e:
        result["Error"] = str(e)
        safe_save_json(result, out_path, logger)
        logger.error(result["Error"])
        return result

    # ----------------------------------------------------------------------
    # 2️⃣ Validate and stage volumes
    # ----------------------------------------------------------------------
    validated = 0
    for region, data in inventories.items():
        vols = data.get("volumes", [])
        logger.info(f"Region {region}: {len(vols)} volumes in manifest.")
        staged = []
        for v in vols:
            # Basic consistency check
            if not v.get("id") or v.get("size_gb") is None:
                logger.warning(f"Skipping invalid volume entry: {v}")
                continue
            staged.append(v)
            validated += 1
        region_out = results_dir / f"volumes_{region}.json"
        with region_out.open("w", encoding="utf-8") as f:
            json.dump(staged, f, indent=2)
        logger.debug(f"Saved {len(staged)} validated volumes → {region_out}")
        result["RegionsProcessed"].append(region)

    # ----------------------------------------------------------------------
    # 3️⃣ Finalize
    # ----------------------------------------------------------------------
    result["ValidatedVolumes"] = validated
    result["Status"] = "SUCCESS" if validated > 0 else "EMPTY"
    result["IntegrityHash"] = safe_save_json(result, out_path, logger)
    logger.info(f"Phase 2 completed — {validated} volumes validated.")
    return result


