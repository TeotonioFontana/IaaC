import json
import hashlib
import boto3
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Any


# -----------------------------------------------------------------------------
# Helpers
# -----------------------------------------------------------------------------
def sha256_file(path: Path) -> str:
    """Return the SHA256 hex digest of a file."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(8192), b""):
            h.update(chunk)
    return h.hexdigest()


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


# -----------------------------------------------------------------------------
# Aggregator Core
# -----------------------------------------------------------------------------
def aggregate_manifests(
    base_dir: Path,
    run_id: str,
    account_id: str,
    profile: str,
    regions: List[str],
    kms_key_alias: str | None = None,
) -> Path:
    """
    Build the unified architecture manifest referencing all per-region sections.

    Parameters
    ----------
    base_dir : Path
        Root directory where phase artifacts are stored (contains /sections/).
    run_id : str
        Identifier of the orchestrator run (UTC timestamp).
    account_id : str
        AWS account ID for traceability.
    profile : str
        AWS CLI/boto3 profile used.
    regions : list[str]
        Regions discovered or specified in the config.
    kms_key_alias : str, optional
        If provided, sign manifest with this AWS KMS key alias.
    """

    sections_meta: Dict[str, Dict[str, Any]] = {}
    total_counts = {"instances_total": 0, "volumes_total": 0, "snapshots_total": 0}
    overall_hasher = hashlib.sha256()

    # Iterate over regions and artifact types
    for region in regions:
        region_dir = base_dir / "sections" / region
        for artifact in ("instances", "volumes", "snapshots"):
            section_path = region_dir / f"{artifact}.json"
            if not section_path.exists():
                continue

            digest = sha256_file(section_path)
            count = len(json.loads(section_path.read_text(encoding="utf-8")))

            sections_meta[f"{region}.{artifact}"] = {
                "path": str(section_path.relative_to(base_dir)),
                "sha256": digest,
                "count": count,
            }
            total_counts[f"{artifact}_total"] = total_counts.get(f"{artifact}_total", 0) + count
            overall_hasher.update(digest.encode())

    manifest = {
        "meta": {
            "manifest_version": "1.0",
            "generated_at": datetime.utcnow().isoformat() + "Z",
            "account_id": account_id,
            "profile": profile,
            "run_id": run_id,
            "regions": regions,
            "sections": sections_meta,
            "overall_checksum": f"sha256:{overall_hasher.hexdigest()}",
        },
        "summary": {
            "regions_total": len(regions),
            **total_counts,
            "errors": 0,
            "warnings": 0,
        },
    }

    manifest_path = base_dir / f"architecture_manifest_{run_id}.json"
    write_json(manifest_path, manifest)

    # Optional: KMS signing
    if kms_key_alias:
        kms = boto3.client("kms", profile_name=profile)
        with manifest_path.open("rb") as f:
            message = f.read()
        resp = kms.sign(
            KeyId=f"alias/{kms_key_alias}",
            Message=message,
            MessageType="RAW",
            SigningAlgorithm="RSASSA_PSS_SHA_256",
        )
        sig_path = manifest_path.with_suffix(".sig")
        sig_path.write_bytes(resp["Signature"])
        manifest["meta"]["signature"] = f"kms://alias/{kms_key_alias}"
        write_json(manifest_path, manifest)

    return manifest_path


# -----------------------------------------------------------------------------
# CLI Entry (optional)
# -----------------------------------------------------------------------------
if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Aggregate per-region manifests")
    parser.add_argument("--base-dir", required=True, help="Root artifact directory")
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--account-id", required=True)
    parser.add_argument("--profile", required=True)
    parser.add_argument("--regions", nargs="+", required=True)
    parser.add_argument("--kms-key-alias", help="Optional KMS key alias for signing")

    args = parser.parse_args()

    path = aggregate_manifests(
        Path(args.base_dir),
        args.run_id,
        args.account_id,
        args.profile,
        args.regions,
        args.kms_key_alias,
    )
    print(f"[OK] Manifest created at: {path}")
